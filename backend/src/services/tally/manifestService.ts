import { createHash } from "crypto";
import { type TallyBatch, type TallyBatchRecord } from "../../models/tally.js";

export function calculateSha256(content: string | Buffer): string {
  return createHash("sha256").update(content).digest("hex");
}

export function verifyChecksum(content: string | Buffer, expectedSha256: string): boolean {
  return calculateSha256(content).toLowerCase() === expectedSha256.toLowerCase();
}

const escCsv = (v: any) => `"${String(v ?? "").replace(/"/g, '""')}"`;

export function generateManifestCsv(batch: TallyBatch): string {
  const metadata = [
    ["Batch ID", batch.id],
    ["Batch Number", batch.batchNumber],
    ["Export Type", batch.exportType],
    ["Report Name", batch.reportName],
    ["Tally Company", batch.companyName],
    ["Generated At", batch.generatedAt],
    ["Generated By", batch.generatedBy || ""],
    ["Status", batch.status],
    ["File Name", batch.fileName],
    ["SHA-256 Checksum", batch.xmlSha256],
    ["File Size (bytes)", String(batch.xmlBytes)],
    ["Total Records", String(batch.recordCount)],
    ["Valid Records", String(batch.validCount)],
    ["Error Records", String(batch.errorCount)],
    ["Warning Count", String(batch.warningCount)],
    ["Taxable Total", batch.totals.taxable.toFixed(2)],
    ["GST Total", batch.totals.gst.toFixed(2)],
    ["Grand Total", batch.totals.grandTotal.toFixed(2)],
    [],
  ];

  const header = [
    "Source ID",
    "Document Number",
    "Date",
    "Party Name",
    "Voucher Type",
    "Amount",
    "Status",
    "Errors",
    "Warnings",
    "Content Hash",
  ];

  const rows = (batch.records || []).map((r: TallyBatchRecord) => [
    r.sourceId,
    r.docNumber || "",
    r.date || "",
    r.party || "",
    r.voucherType,
    Number(r.amount || 0).toFixed(2),
    r.status,
    (r.errors || []).join("; "),
    (r.warnings || []).join("; "),
    r.contentHash,
  ]);

  const metaLines = metadata.map((row) => row.map(escCsv).join(",")).join("\r\n");
  const dataLines = [header, ...rows].map((row) => row.map(escCsv).join(",")).join("\r\n");

  return `${metaLines}\r\n${dataLines}`;
}

export function generateValidationErrorReportCsv(records: any[]): string {
  const header = [
    "Source ID",
    "Document / Name",
    "Voucher Type",
    "Amount",
    "Status",
    "Errors",
    "Warnings",
  ];

  const rows = records.map((r: any) => [
    r.sourceId,
    r.sourceLabel || r.docNumber || "",
    r.voucherType,
    Number(r.amount || 0).toFixed(2),
    r.status,
    (r.errors || []).join("; "),
    (r.warnings || []).join("; "),
  ]);

  return [header, ...rows].map((row) => row.map(escCsv).join(",")).join("\r\n");
}
